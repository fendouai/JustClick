    public static let prompts: [Prompt] = chineseBase + extraChinese + english

    public static func merging(into library: Library) -> Library {
        var result = library
        let ids = Set(library.prompts.map(\.id))
        let titles = Set(library.prompts.map { $0.title.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() })
        result.prompts.append(contentsOf: prompts.filter { !ids.contains($0.id) && !titles.contains($0.title.lowercased()) })
        return result
    }
